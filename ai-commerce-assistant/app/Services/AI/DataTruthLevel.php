<?php

namespace App\Services\AI;

/**
 * Strict Data Truth Classification Constants.
 * Every metric and data point consumed by or output from the AI layer must
 * be stamped with one of these truth levels to prevent hallucinations and ambiguous claims.
 */
class DataTruthLevel
{
    /**
     * Directly observed fact from marketplace APIs or verified database records.
     * Examples: eBay listing price, seller username, currency code, external ID.
     */
    public const OBSERVED = 'OBSERVED';

    /**
     * Exact arithmetic result deterministically computed by Laravel using BCMath precision.
     * Examples: total cost, gross profit, profit margin percentage, ROI.
     */
    public const CALCULATED = 'CALCULATED';

    /**
     * Parametric estimates supplied by the user or derived from industry baseline averages.
     * Examples: estimated shipping cost, platform commission fee percentage.
     */
    public const ESTIMATED = 'ESTIMATED';

    /**
     * Deterministic rule-based algorithmic scoring computed by domain engines.
     * Examples: Opportunity score (0-100), algorithmic risk score, competition tier.
     */
    public const HEURISTIC = 'HEURISTIC';

    /**
     * Qualitative reasoning, synthesis, warnings, and action steps generated by the AI provider.
     * Examples: strategic advice, risk reasoning, executive summary.
     */
    public const AI_GENERATED = 'AI_GENERATED';

    /**
     * All recognized levels.
     *
     * @return array<string>
     */
    public static function all(): array
    {
        return [
            self::OBSERVED,
            self::CALCULATED,
            self::ESTIMATED,
            self::HEURISTIC,
            self::AI_GENERATED,
        ];
    }
}

